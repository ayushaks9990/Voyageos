import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {makeLocalPlan,parsePrompt,estimateBudget} from '../dist/local-planner.js';
const catalog=JSON.parse(await readFile(new URL('../dist/catalog.json',import.meta.url),'utf8'));
const prompt="Plan a 6-day Bali trip for 2 people from Kolkata in December. Budget ₹1.4 lakh. We like beaches, nightlife, adventure and good hotels. Don't make the schedule exhausting.";
const parsed=parsePrompt(prompt,catalog);
assert.equal(parsed.destination,'Bali');assert.equal(parsed.origin,'Kolkata');assert.equal(parsed.budget,140000);
const plan=makeLocalPlan({prompt,start_date:'2030-12-01'},catalog);
assert.equal(plan.days.length,6);assert.equal(plan.budget.total,125810);assert.equal(plan.budget.remaining,14190);
assert.equal(plan.budget.total,plan.budget.items.reduce((s,x)=>s+x.amount,0));
assert.equal(plan.days.at(-1).date,'2030-12-06');
assert.equal(plan.hotels[0].real_property,false);
assert.equal(plan.agents.length,7);assert.equal(plan.flights.length,3);assert.equal(plan.transport.cabs.length,3);
assert.equal(plan.flights[0].label,'Best overall');assert.ok(plan.recommendation.score>=50);
assert.equal(makeLocalPlan({prompt,days:1,start_date:'2030-12-01'},catalog).budget.nights,0);
assert.throws(()=>makeLocalPlan({prompt,days:31},catalog),/30 days/);
assert.throws(()=>makeLocalPlan({prompt,start_date:'2030-02-31'},catalog),/valid future/);
assert.throws(()=>makeLocalPlan({prompt:'Plan a trip to Bali with $3000'},catalog),/INR/);
assert.equal(makeLocalPlan({prompt:'Plan a trip to Kyoto for 5 days. Budget ₹2 lakh.'},catalog).mode,'flexible');
assert.equal(estimateBudget({...plan.brief,budget:1000},catalog[0]).status,'over');
assert.equal(parsePrompt('Plan a trip to Kyoto for 5 days from Tokyo.',catalog).destination,'Kyoto');
console.log('Frontend planner checks passed: parsing, costs, dates, overrides, validation and honest fallback.');
